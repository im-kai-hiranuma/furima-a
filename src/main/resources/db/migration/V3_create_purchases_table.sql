CREATE TABLE IF NOT EXISTS purchases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL UNIQUE, -- 二重購入防止のため UNIQUE 追加
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT, -- RESTRICT に変更
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT -- RESTRICT に変更
);